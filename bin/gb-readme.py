#!/usr/bin/env python3
"""gb-readme — the public README's factual half, DERIVED from the running tool.

WHY THIS EXISTS (measured 2026-09-12). Every count in the public README was hand-typed, and
every one of them had drifted: `24 checks` against a live 25, `54 fixtures` against 55, and a
verb table frozen at nineteen while the CLI reached fifty-seven. The published mirror was worse
— a stale export advertising 18 verbs with a `bin/gb` of 1997 lines against 3233 here — and
nothing could tell the two apart, because `version` is a hand-edited constant that three files
merely agree on.

`bin/gb-gatesdoc.py` now FAILS when a shipped doc's counts disagree with the runner, which
turned every drift into a red gate. That is the right alarm and the wrong remedy: an alarm that
fires on a number a human has to retype will keep firing. The remedy is to stop typing the
number. So the README has two halves, and only one of them is written by a person:

  HANDWRITTEN   the hero, "What this is", "Install", "What it does not do" — judgement, voice,
                and the promises a tool makes. A generator has no business writing these, and
                this file never touches them.
  DERIVED       the verbs, the exit codes, the oracles, the layout, the build stamp. Every one
                is a measurement, so every one comes from `gb capabilities --json`, the gate
                producer, the selftests, and the exporter's own allowlist.

THE MARKERS ARE THE CONTRACT. Derived content lives strictly between
`<!-- gb:derived:begin -->` and `<!-- gb:derived:end -->`. Everything outside is preserved
byte-for-byte — verified by a selftest leg, because a generator that eats prose gets turned off
within a week and then the counts rot again.

`--check` EXITS 1 WHEN THE FILE IS STALE. That is what makes this different from a script
somebody remembers to run: the staleness is detectable by CI and by `gb doctor`, in the same
way the gate's own fixtures are. Regenerating is `gb readme --write`.

WHAT IT DELIBERATELY DOES NOT DERIVE. Prose that makes a claim about the WORLD rather than
about this tree — "one cloud computer per user", "a share link is public" — stays handwritten
and stays outside the markers. Those are vendor facts with citations; deriving them from our own
code would make our code their source, which is exactly backwards.
"""

from __future__ import annotations

import argparse
import ast
import dataclasses
import datetime as dt
import json
import pathlib
import re
import subprocess
import sys
from typing import Any, Callable, Dict, List, Optional, Sequence, Tuple

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import gbtypes  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
BIN = ROOT / "bin"
TARGET = ROOT / "packaging" / "README.public.md"
SCHEMA = "gb-readme/1"

BEGIN = "<!-- gb:derived:begin -->"
END = "<!-- gb:derived:end -->"
WARN = (
    "<!-- Everything between these markers is GENERATED by `gb readme --write`. Do not hand-edit:\n"
    "     `gb readme --check` exits 1 when it drifts, and `gb-gatesdoc.py` fails on a stale count.\n"
    "     Prose outside the markers is handwritten and this generator never touches it. -->"
)

EXIT_STALE = 1
EXIT_USAGE = 2
EXIT_ENVIRONMENT = 3


# ----------------------------------------------------------------------------------------------
# measurement — every number below is read from a producer, never recounted here


class MeasureError(Exception):
    pass


def _run(argv: Sequence[str], timeout_s: int = 300) -> str:
    try:
        p = subprocess.run(
            list(argv), cwd=str(ROOT), capture_output=True, text=True, timeout=timeout_s
        )
    except (OSError, subprocess.TimeoutExpired) as e:
        raise MeasureError(f"{' '.join(argv[:3])}: {type(e).__name__}") from e
    # Exit code is deliberately NOT consulted. `gb triage` exits 1 to CARRY a RED verdict and
    # `--selftest` exits 1 when a fixture fails; the COUNTS in the stream are still the truth,
    # and refusing to read them would make a red board unrenderable.
    if not p.stdout.strip():
        raise MeasureError(f"{' '.join(argv[:3])}: no output (exit {p.returncode})")
    return p.stdout


def _json(argv: Sequence[str], timeout_s: int = 300) -> Dict[str, Any]:
    out = _run(argv, timeout_s)
    try:
        obj = json.loads(out)
    except ValueError as e:
        raise MeasureError(f"{' '.join(argv[:3])}: not JSON ({e})") from e
    if not isinstance(obj, dict):
        raise MeasureError(f"{' '.join(argv[:3])}: envelope is not an object")
    return obj


@dataclasses.dataclass(frozen=True)
class Facts:
    """Everything the derived half of the README states, measured once."""

    version: str
    build: str
    verbs: Dict[str, str]
    exit_codes: Dict[str, str]
    checks: List[str]
    fixtures: int
    selftests: List[Tuple[str, str]]
    trees: List[Tuple[str, str]]
    producers: int


def _build_stamp() -> str:
    """Read `gb --version`'s own stamp rather than recomputing it.

    Recomputing would put a second implementation of the stamp in the tree, and two
    implementations of one number is how the three hand-edited `version` constants came to
    disagree in the first place.
    """
    out = _run([sys.executable, str(BIN / "gb"), "--version"], 120)
    m = re.search(r"build (\S+)", out)
    if not m:
        raise MeasureError("gb --version printed no build stamp")
    return m.group(1)


def _fixture_count() -> int:
    out = _run([sys.executable, str(BIN / "gb-surface-gate.py"), "--selftest"], 600)
    m = re.search(r"(\d+)\s*/\s*(\d+) fixtures", out)
    if not m:
        raise MeasureError("gate selftest printed no N/M fixtures")
    return int(m.group(2))


def _selftests() -> List[Tuple[str, str]]:
    """Every producer that proves itself, with its own reported count.

    Runs them. A README that lists a selftest without running it is asserting the thing the
    selftest exists to assert.
    """
    rows: List[Tuple[str, str]] = []
    for path in sorted(BIN.glob("gb-*.py")) + [BIN / "gbrpc.py"]:
        if not path.is_file():
            continue
        try:
            out = _run([sys.executable, str(path), "--selftest"], 300)
        except MeasureError:
            continue
        last = [ln.strip() for ln in out.strip().splitlines() if ln.strip()]
        if not last:
            continue
        tail = last[-1]
        if "PASS" not in tail.upper():
            continue
        m = re.search(r"(\d+\s*/\s*\d+)", tail)
        rows.append((path.name, m.group(1) if m else "pass"))
    return rows


def _exported_trees() -> List[Tuple[str, str]]:
    """Directories the exporter publishes, read out of the exporter by AST.

    Parsed, not imported: that module mutates `sys.path` at import time and this generator has
    no business executing 1300 lines of publisher to render a table.
    """
    src = (BIN / "gb-export-public.py").read_text()
    out: List[Tuple[str, str]] = []
    for node in ast.walk(ast.parse(src)):
        if not isinstance(node, ast.Call):
            continue
        f = node.func
        if not isinstance(f, ast.Name) or f.id != "Tree":
            continue
        args = [a for a in node.args if isinstance(a, ast.Constant)]
        if len(args) < 2 or not isinstance(args[0].value, str):
            continue
        src_name = args[0].value
        if "/" in src_name or src_name.endswith((".md", ".json", ".sh", ".jpg")):
            continue
        why = next(
            (
                a.value
                for a in reversed(args)
                if isinstance(a.value, str) and " " in a.value
            ),
            "",
        )
        out.append((src_name, why))
    return sorted(set(out))


def measure() -> Facts:
    caps = _json([sys.executable, str(BIN / "gb"), "capabilities", "--json"], 300)
    verbs = caps.get("commands")
    codes = caps.get("exit_codes")
    if not isinstance(verbs, dict) or not verbs:
        raise MeasureError("capabilities carried no commands map")
    if not isinstance(codes, dict) or not codes:
        raise MeasureError("capabilities carried no exit_codes map")
    gate = _json([sys.executable, str(BIN / "gb-surface-gate.py"), "--json"], 600)
    checks = [
        str(c.get("check")) for c in gate.get("checks", []) if isinstance(c, dict)
    ]
    if not checks:
        raise MeasureError("the gate reported no checks")
    return Facts(
        version=str(caps.get("version", "?")),
        build=_build_stamp(),
        verbs={str(k): str(v) for k, v in verbs.items()},
        exit_codes={str(k): str(v) for k, v in codes.items()},
        checks=checks,
        fixtures=_fixture_count(),
        selftests=_selftests(),
        trees=_exported_trees(),
        producers=len(list(BIN.glob("gb-*.py"))),
    )


